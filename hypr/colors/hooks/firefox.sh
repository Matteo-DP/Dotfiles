#!/bin/bash
# Firefox theme hook for Hypr Colors Theme Manager

# Path to the generated userChrome.css (change to your Firefox profile path)
FIREFOX_PROFILE=$(find "$HOME/.mozilla/firefox" -maxdepth 1 -type d -name "*.default-release" | head -n 1)
USERCHROME="$FIREFOX_PROFILE/chrome/userChrome.css"
USERCONTENT="$FIREFOX_PROFILE/chrome/userContent.css"

export SYMLINK_SOURCE="$USERCHROME"
SYMLINK_TARGET="$HOME/.config/hypr/colors/current-theme/userChrome.css"

hook_generate_target() {
    if [ -z $FIREFOX_PROFILE ]; then
        echo "Firefox profile not found. Please ensure Firefox is installed and you have a default profile."
        return 1
    fi
    mkdir -p "$FIREFOX_PROFILE/chrome"
    cat > "$SYMLINK_TARGET" <<EOF
    /* Generated by Hypr Colors Theme Manager */
    :root {
        --color-bg: $COLOR_BACKGROUND;
        --color-fg: $COLOR8;
        --color-accent: $COLOR4;
        --color-text: $COLOR7;
        --color-icon: $COLOR6;
    }

    /* Uniform background for all major UI elements */
    #navigator-toolbox,
    #navigator-toolbox > #nav-bar,
    toolbar,
    .tabbrowser-tab[selected='false'] .tab-background,
    #TabsToolbar,
    #titlebar,
    #sidebar-box,
    #browser,
    #appcontent,
    .findbar,
    .searchbar-textbox,
    .autocomplete-richlistbox,
    .urlbar-input,
    .urlbarView,
    .identity-box,
    .notificationbox,
    .panel-arrowcontent,
    .panel-header,
    .panel-footer,
    .panel-subview-body,
    .panel-list,
    .panel-menu,
    .panel-menuitem,
    .panel-menuitem[checked],
    .panel-menuitem[disabled],
    .panel-menuitem[highlighted],
    .panel-menuitem[selected],
    .panel-menuitem[pressed],
    .panel-menuitem[open],
    .panel-menuitem[active],
    .panel-menuitem[hover],
    .panel-menuitem[focus],
    .panel-menuitem[visited],
    .panel-menuitem[default],
    .panel-menuitem[default][checked],
    .panel-menuitem[default][disabled],
    .panel-menuitem[default][highlighted],
    .panel-menuitem[default][selected],
    .panel-menuitem[default][pressed],
    .panel-menuitem[default][open],
    .panel-menuitem[default][active],
    .panel-menuitem[default][hover],
    .panel-menuitem[default][focus],
    .panel-menuitem[default][visited],
    /* Additional search bar and input elements */
    #urlbar,
    #searchbar,
    #searchbar input,
    #urlbar input,
    #urlbar-background,
    #urlbar-container,
    .urlbarView-row,
    .urlbarView-results,
    .urlbarView,
    .searchbar-textbox,
    .searchbar-engine-one-off-item,
    .autocomplete-richlistbox,
    .autocomplete-richlistitem,
    .autocomplete-textbox,
    .autocomplete-input,
    .textbox-input,
    .textbox,
    .findbar-textbox,
    .findbar,
    .findbar-container,
    .findbar-label,
    .findbar-closebutton,
    .outer-wrapper,
    .findbar-button {
        background-color: var(--color-bg) !important;
        color: var(--color-text) !important;
        border-color: var(--color-bg) !important;
    }

    .tabbrowser-tab[selected="true"] .tab-background {
        background-color: var(--color-fg) !important;
        color: var(--color-text) !important;
    }

    .tab-close-button {
        color: var(--color-text) !important;
    }
EOF
}

hook_post_generate() {
    echo "Firefox theme generated at $USERCHROME. Restart Firefox to apply."
}

export -f hook_generate_target
export -f hook_post_generate
