// On-screen display for volume, microphone and media.
// Scripts trigger it with: ags request -i osd volume | mic | backlight | media [player]
// Audio panel (waybar pulseaudio click): ags request -i osd audio
import app from "ags/gtk4/app"
import { Gtk, Gdk } from "ags/gtk4"
import GLib from "gi://GLib"
import style from "./style.scss"
import Osd, { showVolume, showMic, showBacklight, showMedia } from "./widget/Osd"
import AudioCenter, { toggleAudio, closeAudio } from "./widget/AudioCenter"

// Theme colors live in a separate file so a theme switch can reload them
// without restarting. Generated by ~/.config/hypr/colors/hooks/ags.sh
const colorsPath = `${GLib.get_user_config_dir()}/ags/colors.css`
let colorsProvider: Gtk.CssProvider | null = null

function loadColors() {
  const display = Gdk.Display.get_default()!
  if (colorsProvider) Gtk.StyleContext.remove_provider_for_display(display, colorsProvider)
  colorsProvider = new Gtk.CssProvider()
  if (GLib.file_test(colorsPath, GLib.FileTest.EXISTS)) colorsProvider.load_from_path(colorsPath)
  Gtk.StyleContext.add_provider_for_display(
    display,
    colorsProvider,
    Gtk.STYLE_PROVIDER_PRIORITY_USER,
  )
}

app.start({
  instanceName: "osd",
  css: style,
  main() {
    loadColors()
    Osd()
    AudioCenter()
  },
  requestHandler(argv, res) {
    const [cmd, arg] = argv
    switch (cmd) {
      case "volume":
        showVolume()
        return res("ok")
      case "mic":
        showMic()
        return res("ok")
      case "backlight":
        showBacklight()
        return res("ok")
      case "media":
        return res(showMedia(arg) ? "ok" : "no player")
      case "audio":
        toggleAudio()
        return res("ok")
      case "audio-close":
        closeAudio()
        return res("ok")
      case "reload-css":
        loadColors()
        return res("ok")
      default:
        return res(`unknown request: ${cmd}`)
    }
  },
})
